# frozen_string_literal: true

module ActiveRecord
  module AttributeMethods
    # = Active Record Attribute Methods \Linker
    #
    # Most of the time spent defining attribute methods goes into deciding which
    # methods each model receives, not into compiling them:
    # ActiveSupport::CodeGenerator compiles each distinct method body once and
    # shares it between models. The linker records those decisions in a
    # generated Ruby file, and a booting application binds the recorded methods
    # instead of making the decisions again. The file is ordinary Ruby, so
    # Bootsnap caches its compiled form like any other source file.
    #
    #   $ bin/rails db:attribute_methods:link
    #
    # writes <tt>db/attribute_methods_link.rb</tt>. To use it, set
    #
    #   config.active_record.attribute_methods_link_path = Rails.root.join("db/attribute_methods_link.rb")
    #
    # The file has to be regenerated whenever the schema, a model or Rails
    # changes, so generate it during the build, before precompiling the Bootsnap
    # cache. The whole file is ignored when it was generated by another Rails
    # version. A model is generated as usual when its superclass, attribute
    # names, aliases, readonly attributes or attribute method patterns differ
    # from the recorded ones, or when it has no entry.
    class Linker # :nodoc:
      FORMAT = 1

      Recording = Struct.new(:source, :models)

      class << self
        attr_reader :path

        def path=(path)
          @path = path
          @current = nil
          @loaded = false
        end

        # Called by +define_attribute_methods+ with a block that generates the
        # model's attribute methods. Binds the recorded methods instead when
        # the link file has a matching entry.
        def define_attribute_methods(model, owner)
          # The linker's state lives on the main Ractor.
          if !ActiveSupport::Ractors.main?
            yield
          elsif @recording
            # The key is taken before generating, as Linker::Link#bind does:
            # composite primary key models alias +id_value+ while defining.
            key = model_key(model)
            ActiveSupport::CodeGenerator.recorder.take_methods(owner)
            yield
            @recording[model] = [key, ActiveSupport::CodeGenerator.recorder.take_methods(owner)]
          elsif !current&.bind(model, owner)
            yield
          end
        end

        # Records the attribute methods defined while the block runs, and
        # returns a Recording whose +source+ is the link file. Only methods
        # defined for the first time are recorded, so run the block before
        # anything has defined attribute methods: boot the application inside
        # it, then call +define_attribute_methods+ on the models to link.
        def record
          recorded = {}
          sources = nil
          ActiveSupport::CodeGenerator.record do |recorder|
            @recording = recorded
            yield
            sources = recorder.sources
          ensure
            @recording = nil
          end
          Recording.new(generate(sources, recorded), recorded.keys)
        end

        # Called by the link file. Yields a Link to fill in when the file was
        # generated by this version of Rails.
        def link(key)
          return unless key == global_key

          @current = Link.new
          yield @current
        end

        def global_key
          [FORMAT, ActiveRecord.version.to_s, ActiveRecord._raise_on_assign_to_attr_readonly]
        end

        def model_key(model)
          [
            model.superclass.name,
            model.attribute_names,
            model.aliases_by_attribute_name,
            model.readonly_attributes,
            model.attribute_method_patterns.map { |pattern| [pattern.prefix, pattern.suffix] },
          ]
        end

        private
          def current
            return @current if @loaded

            @loaded = true
            load(@path.to_s) if @path && File.exist?(@path)
            @current
          end

          def generate(sources, recorded)
            bodies = []
            body_index = {}
            models = {}

            recorded.each do |model, (key, methods)|
              next unless model.name

              bindings = []
              methods.each do |namespace, as, canonical_name|
                index = body_index[[namespace, canonical_name]] ||= (bodies << [namespace, canonical_name]).size - 1
                bindings << index << (as == canonical_name ? nil : as)
              end
              models[model.name] = [key, bindings]
            end

            attr_names = ActiveModel::AttributeMethods::AttrNames.constants.grep(/\AATTR_/).sort.index_with do |name|
              ActiveModel::AttributeMethods::AttrNames.const_get(name)
            end

            output = +<<~RUBY
              # frozen_string_literal: true

              # This file was generated by `bin/rails db:attribute_methods:link`.
              # Regenerate it instead of editing it.

              ActiveRecord::AttributeMethods::Linker.link(#{global_key.inspect}) do |link|
                link.attr_names(#{attr_names.inspect})
            RUBY

            bodies.group_by(&:first).each do |namespace, canonical_names|
              output << "\n  link.bodies(#{namespace.inspect}) do\n"
              canonical_names.each do |_, canonical_name|
                output << sources.fetch(namespace).fetch(canonical_name) << "\n"
              end
              output << "  end\n"
            end

            # One body and one model per line, so regenerating the file gives a
            # readable diff.
            output << "\n  link.models(\n    [\n"
            bodies.each { |body| output << "      #{body.inspect},\n" }
            output << "    ],\n    {\n"
            models.sort.each { |name, entry| output << "      #{name.inspect} => #{entry.inspect},\n" }
            output << "    }\n  )\nend\n"
          end
      end

      class Link # :nodoc:
        def initialize
          @models = {}
          @modules = {}
        end

        def attr_names(constants)
          constants.each do |name, attr_name|
            ActiveModel::AttributeMethods::AttrNames.const_set(name, attr_name) unless ActiveModel::AttributeMethods::AttrNames.const_defined?(name, false)
          end
        end

        # Defines the method bodies in the block on a module of the link's
        # own, which models bind from directly. The bodies are not copied into
        # ActiveSupport::CodeGenerator's method caches: copying them all costs
        # more than compiling the few a model that falls back may need again.
        def bodies(namespace, &block)
          (@modules[namespace] ||= Module.new).module_eval(&block)
        end

        def models(bodies, models)
          @methods = bodies.map do |namespace, canonical_name|
            [canonical_name, @modules.fetch(namespace).instance_method(canonical_name)]
          end
          @models = models
        end

        # Binds +model+'s recorded methods into +owner+ and returns true, or
        # returns false when there is no matching entry. An entry is used at
        # most once, so methods defined again after a reset are generated.
        def bind(model, owner)
          name = model.name or return false
          key, bindings = @models.delete(name)
          return false unless key && key == Linker.model_key(model)

          index = 0
          while index < bindings.size
            canonical_name, method = @methods[bindings[index]]
            owner.define_method(bindings[index + 1] || canonical_name, method)
            index += 2
          end
          # Bound methods keep their bodies alive; the lookup tables are only
          # needed while entries remain.
          @methods = @modules = nil if @models.empty?
          true
        end
      end
    end
  end
end
